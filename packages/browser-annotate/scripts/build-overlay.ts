import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Bundles the page overlays (DOM code) into string modules, so Node programs that install them
 * never type-check or import DOM sources: `src/overlay` (annotate mode) and `src/cursor` (the
 * agent cursor). `--check` fails when a committed bundle no longer matches its sources.
 */
const check = process.argv.slice(2).includes("--check");
const bundles = [
  {
    entry: "../src/overlay/main.ts",
    output: "../src/overlay-bundle.gen.ts",
    name: "overlayBundle",
  },
  { entry: "../src/cursor/main.ts", output: "../src/cursor-bundle.gen.ts", name: "cursorBundle" },
];

let stale = false;
for (const bundle of bundles) {
  const output = fileURLToPath(new URL(bundle.output, import.meta.url));
  const result = await build({
    entryPoints: [fileURLToPath(new URL(bundle.entry, import.meta.url))],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "chrome120",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
  });
  const code = result.outputFiles[0]?.text.trim();
  if (!code) throw new Error(`${bundle.entry} bundle is empty`);
  const source = `// Generated by packages/browser-annotate/scripts/build-overlay.ts from ${bundle.entry.replace("../", "").replace(/\/main\.ts$/, "")}.
// Do not edit. Rebuild with: bun run --filter @ace/browser-annotate build
export const ${bundle.name} = ${JSON.stringify(code)};
`;
  if (check) {
    const current = await readFile(output, "utf8").catch(() => "");
    if (current !== source) stale = true;
  } else {
    await writeFile(output, source);
    console.log(`Wrote ${output} (${code.length} bytes)`);
  }
}
if (check) {
  if (stale) {
    console.error(
      "A page overlay bundle is stale. Run: bun run --filter @ace/browser-annotate build",
    );
    process.exitCode = 1;
  } else console.log("Page overlay bundles are current");
}
