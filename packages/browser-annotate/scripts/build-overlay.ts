import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Bundles `src/overlay` (DOM code) into one string module, so Node programs that install the
 * overlay never type-check or import DOM sources. `--check` fails when the committed bundle
 * no longer matches its sources.
 */
const entry = fileURLToPath(new URL("../src/overlay/main.ts", import.meta.url));
const output = fileURLToPath(new URL("../src/overlay-bundle.gen.ts", import.meta.url));
const check = process.argv.slice(2).includes("--check");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "chrome120",
  minify: true,
  legalComments: "none",
  charset: "utf8",
  write: false,
});
const code = result.outputFiles[0]?.text.trim();
if (!code) throw new Error("Overlay bundle is empty");
const source = `// Generated by packages/browser-annotate/scripts/build-overlay.ts from src/overlay.
// Do not edit. Rebuild with: bun run --filter @ace/browser-annotate build
export const overlayBundle = ${JSON.stringify(code)};
`;
if (check) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== source) {
    console.error(
      "The annotation overlay bundle is stale. Run: bun run --filter @ace/browser-annotate build",
    );
    process.exitCode = 1;
  } else console.log("Annotation overlay bundle is current");
} else {
  await writeFile(output, source);
  console.log(`Wrote ${output} (${code.length} bytes)`);
}
