test("Paginated Codex rollouts import real prompts, use index names, hide exec and subagents, and search older titles", async () => {
  const env = await environment();
  cleanup.push(env.close);
  const home = join(env.root, "codex");
  const records = codexRecords();
  const first = object(records[0]);
  await jsonl(join(home, "sessions/rollout.jsonl"), [
    { ...first, payload: { id: nativeId, cwd, history_mode: "paginated", source: "vscode" } },
    ...records.slice(1).map((value) => {
      const r = object(value),
        p = object(r.payload);
      return r.type === "response_item" && p.type === "message" && p.role === "user"
        ? Object.assign({}, r, {
            payload: Object.assign({}, p, {
              content: [{ type: "input_text", text: plugins + "\nFix the retry loop" }],
            }),
          })
        : r;
    }),
  ]);
  await jsonl(join(home, "sessions/exec.jsonl"), [
    { type: "session_meta", payload: { id: otherId, cwd, source: "exec" } },
    ...records.slice(1),
  ]);
  await jsonl(join(home, "sessions/subagent.jsonl"), [
    {
      type: "session_meta",
      payload: {
        id: "00000000-0000-0000-0000-000000000003",
        cwd,
        source: { subagent: { other: "guardian" } },
      },
    },
    ...records.slice(1),
  ]);
  await jsonl(join(home, "session_index.jsonl"), [
    { id: nativeId, thread_name: "Retry loop audit", updated_at: "2026-10-08T12:00:00Z" },
  ]);
  const statePath = join(home, "state_5.sqlite");
  const state = new DatabaseSync(statePath);
  state.exec("CREATE TABLE threads(id TEXT,cwd TEXT,title TEXT,updated_at INTEGER)");
  state.prepare("INSERT INTO threads VALUES(?,?,?,?)").run(nativeId, cwd, "State title", 1);
  state.close();
  const service = await env.start([{ id: "codex", provider: "codex", homeDir: home }]);
  await service.scan();
  const sessions = (await service.list({ type: "history.list", cwd, openableOnly: true })).sessions;
  expect(sessions.map((s) => s.title)).toEqual(["Retry loop audit"]);
  const root = sessions[0];
  if (!root) throw new Error("Missing session");
  const sink = memorySink();
  await service.importSession(init(root.id), sink);
  expect(text(sink.items)).toBe("Fix the retry loop codex answer");
  expect(sink.thread?.title).toBe("Retry loop audit");
  expect(
    (await service.list({ type: "history.list", cwd, search: "AUDIT" })).sessions,
  ).toHaveLength(1);
  expect((await service.list({ type: "history.list", cwd, search: "missing" })).sessions).toEqual(
    [],
  );
  const changedState = new DatabaseSync(statePath);
  changedState.prepare("UPDATE threads SET title=?").run("Changed state title");
  changedState.close();
  await service.scan();
  expect((await service.list({ type: "history.list", cwd })).sessions[0]?.title).toBe(
    "Retry loop audit",
  );
  await jsonl(join(home, "session_index.jsonl"), [
    { id: nativeId, thread_name: "Renamed retry audit" },
  ]);
  await service.scan();
  expect((await service.list({ type: "history.list", cwd })).sessions[0]?.title).toBe(
    "Renamed retry audit",
  );
});

test.each(["coexisting", "v2 only"])(
  "OpenCode %s imports ordered user text, reasoning and completed tool results without duplicate legacy messages",
  async (storage) => {
    const env = await environment();
    cleanup.push(env.close);
    const home = join(env.root, "opencode");
    await mkdir(home);
    const path = join(home, "opencode.db");
    const db = new DatabaseSync(path);
    db.exec(`CREATE TABLE session(id TEXT PRIMARY KEY,directory TEXT,title TEXT,time_updated INTEGER,parent_id TEXT);
    CREATE TABLE message(id TEXT PRIMARY KEY,session_id TEXT,time_created INTEGER,data TEXT);
    CREATE TABLE part(id TEXT PRIMARY KEY,message_id TEXT,data TEXT);
    CREATE TABLE session_message(id TEXT PRIMARY KEY,session_id TEXT,type TEXT,seq INTEGER,data TEXT);`);
    const session = db.prepare("INSERT INTO session VALUES(?,?,?,?,?)");
    session.run("root", cwd, "New session", 1000000, null);
    session.run("noise", cwd, "Noise", 1000001, null);
    session.run("child", cwd, "Background review", 1000002, "root");
    const message = db.prepare("INSERT INTO session_message VALUES(?,?,?,?,?)");
    message.run(
      "u1",
      "root",
      "user",
      1,
      JSON.stringify({ text: caveat + "\nAudit the background runner", time: { created: 1 } }),
    );
    message.run(
      "a1",
      "root",
      "assistant",
      2,
      JSON.stringify({
        content: [
          { type: "reasoning", text: "Checking the exit signal" },
          {
            type: "tool",
            id: "tool1",
            name: "read",
            state: {
              status: "completed",
              input: { filePath: "runner.ts" },
              content: [{ type: "text", text: "stored tool output" }],
            },
          },
          { type: "text", text: "The runner waits for its shell" },
        ],
        time: { created: 2 },
      }),
    );
    message.run("n1", "noise", "user", 1, JSON.stringify({ text: plugins }));
    message.run("c1", "child", "user", 1, JSON.stringify({ text: "Check the child" }));
    db.prepare("INSERT INTO message VALUES(?,?,?,?)").run(
      "legacy",
      "root",
      1,
      JSON.stringify({ role: "user" }),
    );
    db.prepare("INSERT INTO part VALUES(?,?,?)").run(
      "legacy-text",
      "legacy",
      JSON.stringify({ type: "text", text: "Duplicate legacy prompt" }),
    );
    if (storage === "v2 only") db.exec("DROP TABLE message; DROP TABLE part");
    db.close();
    const before = await readFile(path);
    const service = await env.start([{ id: "oc", provider: "opencode", homeDir: home }]);
    await service.scan();
    const sessions = (await service.list({ type: "history.list", cwd })).sessions;
    expect(sessions.map((s) => s.title)).toEqual(["Audit the background runner"]);
    const root = sessions[0];
    if (!root) throw new Error("Missing root");
    const sink = memorySink();
    await service.importSession(init(root.id), sink);
    expect(text(sink.items)).toBe(
      "Audit the background runner The runner waits for its shell Check the child",
    );
    expect(
      sink.items.some((i) => i.type === "reasoning" && i.text === "Checking the exit signal"),
    ).toBe(true);
    expect(
      sink.items.some(
        (i) => i.type === "tool_call" && i.call.status === "succeeded" && i.call.title === "read",
      ),
    ).toBe(true);
    expect(
      sink.items.some(
        (i) => i.type === "notice" && i.toolCallId && i.text === "stored tool output",
      ),
    ).toBe(true);
    expect(await readFile(path)).toEqual(before);
  },
);

