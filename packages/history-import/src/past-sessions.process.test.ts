test("Claude summaries take priority, context-only and sidechain sessions stay hidden, and imported prompts are cleaned", async () => {
  const env = await environment();
  cleanup.push(env.close);
  const home = join(env.root, "claude");
  const path = join(home, "projects/p", nativeId + ".jsonl");
  await jsonl(path, [
    ...claudeRecords(plugins + "\n" + caveat + "\nFix reconnect retries"),
    { type: "summary", summary: "Repair reconnect backoff" },
  ]);
  await jsonl(
    join(home, "projects/p/noise.jsonl"),
    claudeRecords(plugins + "\n" + caveat, "noise"),
  );
  await jsonl(
    join(home, "projects/p/sidechain.jsonl"),
    claudeRecords("Background review", "sidechain").map((r) =>
      Object.assign({}, r, { isSidechain: true }),
    ),
  );
  await jsonl(join(home, "projects/p/untitled.jsonl"), [
    ...claudeRecords("Check replay order", "untitled"),
    { type: "ai-title", aiTitle: "Untitled session" },
  ]);
  const before = await readFile(path);
  const service = await env.start([{ id: "claude", provider: "claude", homeDir: home }]);
  await service.scan();
  const sessions = (await service.list({ type: "history.list", cwd })).sessions;
  expect(sessions.map((s) => s.title).toSorted()).toEqual([
    "Check replay order",
    "Repair reconnect backoff",
  ]);
  const root = sessions.find((s) => s.nativeId === nativeId);
  if (!root) throw new Error("Missing root");
  const sink = memorySink();
  await service.importSession(init(root.id), sink);
  expect(text(sink.items)).toBe("Fix reconnect retries answer");
  expect(await readFile(path)).toEqual(before);
});

