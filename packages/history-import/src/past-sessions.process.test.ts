test("A readable root with an unreadable child is excluded from openable results with an explanation", async () => {
  const env = await environment();
  cleanup.push(env.close);
  const home = join(env.root, "codex");
  await jsonl(join(home, "sessions/root.jsonl"), codexRecords());
  await jsonl(join(home, "sessions/child.jsonl"), [
    {
      type: "session_meta",
      payload: {
        id: otherId,
        cwd,
        parent_thread_id: nativeId,
        history_base: { thread_id: nativeId, ordinal: 5 },
      },
    },
    ...codexRecords().slice(1),
  ]);
  const service = await env.start([{ id: "cx", provider: "codex", homeDir: home }]);
  await service.scan();
  expect((await service.list({ type: "history.list", cwd, openableOnly: true })).sessions).toEqual(
    [],
  );
  expect((await service.list({ type: "history.list", cwd })).sessions[0]?.support).toMatchObject({
    status: "unsupported",
    reason: expect.stringContaining("Part of this session"),
  });
});
