import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Bundles the video extension's service worker and offscreen document (`video-extension/`,
 * ADR 0088) into one generated string module, so the daemon writes the unpacked extension without
 * a build step. `--check` fails when the committed bundle no longer matches its sources.
 */
const source = (name: string) =>
  fileURLToPath(new URL(`../video-extension/${name}`, import.meta.url));
const output = fileURLToPath(new URL("../src/video-extension.gen.ts", import.meta.url));
const check = process.argv.slice(2).includes("--check");

async function bundle(entry: string): Promise<string> {
  const result = await build({
    entryPoints: [source(entry)],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "chrome125",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
  });
  const code = result.outputFiles[0]?.text.trim();
  if (!code) throw new Error(`${entry} bundle is empty`);
  return code;
}

const files = {
  "worker.js": await bundle("worker.ts"),
  "offscreen.js": await bundle("offscreen.ts"),
  "offscreen.html":
    '<!doctype html>\n<meta charset="utf-8">\n<script src="offscreen.js"></script>\n',
};
const text = `// Generated by packages/browser/scripts/build-video-extension.ts from video-extension/.
// Do not edit. Rebuild with: node packages/browser/scripts/build-video-extension.ts
export const videoExtensionFiles: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};
`;
if (check) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== text) {
    console.error(
      "The video extension bundle is stale. Run: node packages/browser/scripts/build-video-extension.ts",
    );
    process.exitCode = 1;
  } else console.log("video extension bundle is current");
} else {
  await writeFile(output, text);
  console.log(`Wrote ${output}`);
}
