import { z } from "zod";

/**
 * "Use my Chrome" (ADR 0084): the ace extension in the person's own browser, its native
 * messaging host, and the daemon. The host relays these messages unchanged in both directions.
 */
export const userBrowserHostName = "dev.ace.user_browser";
export const userBrowserProtocolVersion = 1;
/** Chrome's limit on one host-to-extension native message. */
export const userBrowserNativeMessageLimit = 1024 * 1024;
/** Tabs one browser reports at once: far above what a person shares, still bounded. */
export const userBrowserTabLimit = 512;

const id = z.string().min(1).max(256);
const url = z.string().max(8192);
const tabId = z.number().int().nonnegative();
/** A child debugger session of a controlled tab: one of its out-of-process iframes. */
const sessionId = z.string().min(1).max(128);

export const UserBrowserFamily = z.enum([
  "chrome",
  "edge",
  "brave",
  "chromium",
  "arc",
  "vivaldi",
  "opera",
  "other",
]);
export type UserBrowserFamily = z.infer<typeof UserBrowserFamily>;

/** `shared`: the person shared it. `agent`: an agent opened it in the ace window. */
export const UserBrowserAccess = z.enum(["shared", "agent"]);
export type UserBrowserAccess = z.infer<typeof UserBrowserAccess>;

export const UserBrowserTab = z.object({
  tabId,
  windowId: z.number().int(),
  url,
  title: z.string().max(1024),
  active: z.boolean(),
  access: UserBrowserAccess,
  /** The debugger is attached: an agent controls the tab. */
  attached: z.boolean(),
  /** The agent tab whose page opened this one (a `target=_blank` link, `window.open`). */
  openerTabId: tabId.optional(),
  /** The tab plays sound, and whether it is muted. Agent tabs open muted. */
  audible: z.boolean().optional(),
  muted: z.boolean().optional(),
});
export type UserBrowserTab = z.infer<typeof UserBrowserTab>;

/**
 * A download a controlled tab started, as the person's browser saved it. The file stays where
 * the browser put it (`path`); ace only reports it.
 */
export const UserBrowserDownload = z.object({
  id: z.number().int().nonnegative(),
  filename: z.string().max(256),
  path: z.string().max(4096),
  state: z.enum(["in_progress", "complete", "interrupted"]),
  bytes: z.number().int().nonnegative(),
  mimeType: z.string().max(256),
});
export type UserBrowserDownload = z.infer<typeof UserBrowserDownload>;

export const UserBrowserIdentity = z.object({
  family: UserBrowserFamily,
  version: z.string().max(64),
  /** Random, generated by the extension per browser profile. Never a path or account. */
  profileId: id,
  extensionVersion: z.string().max(64),
});
export type UserBrowserIdentity = z.infer<typeof UserBrowserIdentity>;

export const UserBrowserDetachReason = z.enum([
  "closed",
  "revoked",
  "stopped",
  "canceled",
  "sensitive",
  "unreachable",
]);
export type UserBrowserDetachReason = z.infer<typeof UserBrowserDetachReason>;

export const UserBrowserRegister = z.object({
  type: z.literal("user_browser.register"),
  requestId: id,
  version: z.literal(userBrowserProtocolVersion),
  browser: UserBrowserIdentity,
});
export const UserBrowserReply = z.union([
  z.object({ type: z.literal("user_browser.reply"), id, ok: z.literal(true), result: z.unknown() }),
  z.object({
    type: z.literal("user_browser.reply"),
    id,
    ok: z.literal(false),
    error: z.string().max(2048),
  }),
]);
export const UserBrowserEvent = z.object({
  type: z.literal("user_browser.event"),
  event: z.discriminatedUnion("kind", [
    z.object({ kind: z.literal("tabs"), tabs: z.array(UserBrowserTab).max(userBrowserTabLimit) }),
    z.object({
      kind: z.literal("cdp"),
      tabId,
      /** Set for an event of one of the tab's out-of-process iframes. */
      sessionId: sessionId.optional(),
      method: id,
      params: z.unknown(),
    }),
    z.object({ kind: z.literal("detached"), tabId, reason: UserBrowserDetachReason }),
    z.object({ kind: z.literal("download"), tabId, download: UserBrowserDownload }),
  ]),
});
/** From the extension, through the host, to the daemon. */
export const UserBrowserExtensionMessage = z.union([
  UserBrowserRegister,
  UserBrowserReply,
  UserBrowserEvent,
]);
export type UserBrowserExtensionMessage = z.infer<typeof UserBrowserExtensionMessage>;

export const UserBrowserOperation = z.discriminatedUnion("op", [
  z.object({ op: z.literal("tabs.list") }),
  z.object({ op: z.literal("tabs.open"), url: url.optional() }),
  z.object({ op: z.literal("tabs.attach"), tabId }),
  z.object({ op: z.literal("tabs.detach"), tabId }),
  z.object({ op: z.literal("tabs.close"), tabId }),
  /** The person turns a controlled tab's sound off or on. */
  z.object({ op: z.literal("tabs.mute"), tabId, muted: z.boolean() }),
  z.object({
    op: z.literal("cdp"),
    tabId,
    /** Sends to one of the tab's out-of-process iframes instead of the tab itself. */
    sessionId: sessionId.optional(),
    method: id,
    params: z.record(z.string(), z.unknown()).optional(),
  }),
  z.object({ op: z.literal("stop") }),
]);
export type UserBrowserOperation = z.infer<typeof UserBrowserOperation>;

export const UserBrowserRegistered = z.object({
  type: z.literal("user_browser.registered"),
  requestId: id,
  connectionId: id,
});
export const UserBrowserCommand = z.object({
  type: z.literal("user_browser.command"),
  id,
  operation: UserBrowserOperation,
});
/** From the daemon, through the host, to the extension. */
export const UserBrowserDaemonMessage = z.union([UserBrowserRegistered, UserBrowserCommand]);
export type UserBrowserDaemonMessage = z.infer<typeof UserBrowserDaemonMessage>;

/** From the host to the extension only: the state of its daemon link. */
export const UserBrowserLink = z.object({
  type: z.literal("user_browser.link"),
  state: z.enum(["connecting", "connected", "unauthorized", "unavailable"]),
  detail: z.string().max(512).optional(),
});
export type UserBrowserLink = z.infer<typeof UserBrowserLink>;

/** What the host may write to the extension. */
export const UserBrowserToExtension = z.union([UserBrowserDaemonMessage, UserBrowserLink]);
export type UserBrowserToExtension = z.infer<typeof UserBrowserToExtension>;

export const UserBrowserConnection = z.object({
  connectionId: id,
  browser: UserBrowserIdentity,
  connectedAt: z.number().int().nonnegative(),
  tabs: z.array(UserBrowserTab).max(userBrowserTabLimit),
});
export type UserBrowserConnection = z.infer<typeof UserBrowserConnection>;

export const UserBrowserHostInstall = z.object({
  browser: z.string().max(64),
  manifestPath: z.string().max(4096),
});
export const UserBrowserStatus = z.object({
  /** Native messaging install is supported on this daemon's platform. */
  supported: z.boolean(),
  extensionId: z.string().max(64),
  /** The unpacked extension directory to load, once installed. */
  extensionPath: z.string().max(4096).optional(),
  installed: z.array(UserBrowserHostInstall).max(32),
  connections: z.array(UserBrowserConnection).max(8),
});
export type UserBrowserStatus = z.infer<typeof UserBrowserStatus>;

export const UserBrowserSettings = z.object({
  type: z.literal("user_browser.settings"),
  requestId: z.string().min(1).max(128),
  operation: z.enum(["status", "install", "revoke", "stop"]),
});
export type UserBrowserSettings = z.infer<typeof UserBrowserSettings>;
export const UserBrowserSettingsResult = z.object({
  type: z.literal("user_browser.settings.result"),
  requestId: z.string().min(1).max(128),
  result: z.discriminatedUnion("kind", [
    z.object({ kind: z.literal("status"), status: UserBrowserStatus }),
    z.object({
      kind: z.literal("error"),
      code: z.enum(["forbidden", "unsupported", "unavailable", "failed"]),
      message: z.string().max(512),
    }),
  ]),
});
export type UserBrowserSettingsResult = z.infer<typeof UserBrowserSettingsResult>;
