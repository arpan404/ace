/** Keep the native pointer on the same geometry as computer-use and browser-use icons. */
import { readFile, writeFile } from "node:fs/promises";
import { agentCursorPath, agentCursorOutline, agentCursorTip, glyphBox } from "../src/glyphs.ts";

const tokens = agentCursorPath.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?/g) ?? [];
const lines: string[] = [];
let index = 0;
let x = 0;
let y = 0;
let startX = 0;
let startY = 0;
let command = "";
const number = () => {
  const token = tokens[index++];
  const value = Number(token);
  if (token === undefined || !Number.isFinite(value)) throw new Error("Invalid cursor geometry");
  return value;
};
const point = (px: number, py: number) =>
  `CGPoint(x: ${Number(px.toFixed(5))}, y: ${Number(py.toFixed(5))})`;
while (index < tokens.length) {
  if (/^[a-zA-Z]$/.test(tokens[index] ?? "")) command = tokens[index++] ?? "";
  const relative = command === command.toLowerCase();
  const ox = relative ? x : 0;
  const oy = relative ? y : 0;
  switch (command.toLowerCase()) {
    case "m": {
      x = number() + ox;
      y = number() + oy;
      startX = x;
      startY = y;
      lines.push(`        path.move(to: ${point(x, y)})`);
      command = relative ? "l" : "L";
      break;
    }
    case "l":
      x = number() + ox;
      y = number() + oy;
      lines.push(`        path.line(to: ${point(x, y)})`);
      break;
    case "c": {
      const ax = number() + ox,
        ay = number() + oy;
      const bx = number() + ox,
        by = number() + oy;
      x = number() + ox;
      y = number() + oy;
      lines.push(
        `        path.curve(to: ${point(x, y)}, controlPoint1: ${point(ax, ay)}, controlPoint2: ${point(bx, by)})`,
      );
      break;
    }
    case "z":
      lines.push("        path.close()");
      x = startX;
      y = startY;
      command = "";
      break;
    default:
      throw new Error(`Unsupported cursor command ${command}`);
  }
}
const output = `// Generated by packages/design-tokens/scripts/generate-native-cursor.ts from @ace/design-tokens/glyphs. Edit the shared source.\nimport AppKit\n\nenum CUAgentCursorGlyph {\n    static let box: CGFloat = ${glyphBox}\n    static let outline: CGFloat = ${agentCursorOutline}\n    static let tip = ${point(agentCursorTip.x, agentCursorTip.y)}\n\n    static func path() -> NSBezierPath {\n        let path = NSBezierPath()\n${lines.join("\n")}\n        return path\n    }\n}\n`;
const destination = new URL(
  "../../../native/screen-helper/ComputerCursorGlyph.swift",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output)
    throw new Error(
      "Native cursor is stale; run node packages/design-tokens/scripts/generate-native-cursor.ts",
    );
} else {
  await writeFile(destination, output);
}
