/** Keep the native pointer on the same geometry as computer-use and browser-use icons. */
import { readFile, writeFile } from "node:fs/promises";
import { agentCursorPath, agentCursorOutline, agentCursorTip, glyphBox } from "../src/glyphs.ts";
import { glyphCommands, type GlyphPoint } from "../src/glyph-path.ts";

const point = (at: GlyphPoint) =>
  `CGPoint(x: ${Number(at.x.toFixed(5))}, y: ${Number(at.y.toFixed(5))})`;
const lines = glyphCommands(agentCursorPath).map((step) => {
  switch (step.kind) {
    case "move":
      return `        path.move(to: ${point(step.to)})`;
    case "line":
      return `        path.line(to: ${point(step.to)})`;
    case "curve":
      return `        path.curve(to: ${point(step.to)}, controlPoint1: ${point(step.control1)}, controlPoint2: ${point(step.control2)})`;
    case "close":
      return "        path.close()";
  }
});
const output = `// Generated by packages/design-tokens/scripts/generate-native-cursor.ts from @ace/design-tokens/glyphs. Edit the shared source.\nimport AppKit\n\nenum CUAgentCursorGlyph {\n    static let box: CGFloat = ${glyphBox}\n    static let outline: CGFloat = ${agentCursorOutline}\n    static let tip = ${point(agentCursorTip)}\n\n    static func path() -> NSBezierPath {\n        let path = NSBezierPath()\n${lines.join("\n")}\n        return path\n    }\n}\n`;
const destination = new URL(
  "../../../native/screen-helper/ComputerCursorGlyph.swift",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output)
    throw new Error(
      "Native cursor is stale; run node packages/design-tokens/scripts/generate-native-cursor.ts",
    );
} else {
  await writeFile(destination, output);
}
