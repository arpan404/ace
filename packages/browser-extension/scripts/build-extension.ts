import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Bundles ace for Chrome's service worker and popup (`extension/`) into one generated string
 * module, so the daemon writes the unpacked extension without a build step. `--check` fails when
 * the committed bundle no longer matches its sources.
 */
const source = (name: string) => fileURLToPath(new URL(`../extension/${name}`, import.meta.url));
const output = fileURLToPath(new URL("../src/extension-bundle.gen.ts", import.meta.url));
const check = process.argv.slice(2).includes("--check");

async function bundle(entry: string): Promise<string> {
  const result = await build({
    entryPoints: [source(entry)],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "chrome125",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
  });
  const code = result.outputFiles[0]?.text.trim();
  if (!code) throw new Error(`${entry} bundle is empty`);
  return code;
}

const files = {
  "background.js": await bundle("background.ts"),
  "popup.js": await bundle("popup.ts"),
  "popup.html": await readFile(source("popup.html"), "utf8"),
};
const text = `// Generated by packages/browser-extension/scripts/build-extension.ts from extension/.
// Do not edit. Rebuild with: bun run --filter @ace/browser-extension build
export const extensionFiles: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};
`;
if (check) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== text) {
    console.error(
      "The ace for Chrome bundle is stale. Run: bun run --filter @ace/browser-extension build",
    );
    process.exitCode = 1;
  } else console.log("ace for Chrome bundle is current");
} else {
  await writeFile(output, text);
  console.log(`Wrote ${output}`);
}
