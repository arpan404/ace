import AppKit

/// One pasteboard type and its bytes.
struct CUClipboardEntry: Codable, Equatable {
    let type: String
    let data: Data
}

/// One pasteboard item with its types in the order the app that wrote it gave them, which is
/// the order of preference readers use.
struct CUClipboardItem: Codable, Equatable {
    let entries: [CUClipboardEntry]
}

/// The person's clipboard as saved before an agent paste. Written to disk before the
/// clipboard is replaced, so it can be put back even if the helper is killed mid-paste.
struct CUClipboardSave: Codable, Equatable {
    /// The helper process that saved it.
    let owner: Int32
    /// Marks the agent's content on the pasteboard: restore only while it is still there.
    let token: String
    let items: [CUClipboardItem]
    /// Types whose data could not be read (promises from apps that no longer answer).
    let unreadable: [String]
}

func cuEncodeClipboardSave(_ save: CUClipboardSave) throws -> Data {
    let encoder = PropertyListEncoder()
    encoder.outputFormat = .binary
    return try encoder.encode(save)
}

func cuDecodeClipboardSave(_ data: Data) -> CUClipboardSave? { try? PropertyListDecoder().decode(CUClipboardSave.self, from: data) }

/// Whether a saved clipboard should be put back now: only while the pasteboard still holds
/// exactly the agent's content (anything the person copied since wins), and, for a leftover
/// from another helper, only once that helper is gone.
func cuShouldRestore(_ save: CUClipboardSave, boardToken: String?, ownerAlive: Bool, isMine: Bool) -> Bool {
    guard boardToken == save.token else { return false }
    return isMine || !ownerAlive
}

/// Pasteboard types that tell clipboard managers to ignore the agent's temporary content,
/// and the private type carrying the agent's token.
let cuTransientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
let cuAutoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
let cuAgentTokenType = NSPasteboard.PasteboardType("dev.ace.screen-helper.paste-token")

/// Reads, writes and restores the general pasteboard for agent pastes.
@MainActor enum CUClipboard {
    static var directory: URL { URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("ace-screen-helper", isDirectory: true) }
    static var lockPath: String { URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("ace-screen-helper-clipboard.lock").path }
    /// The save of a paste in progress, restored on SIGTERM, SIGINT or stdin EOF.
    static var pending: (save: CUClipboardSave, file: URL)?

    static func snapshot(_ board: NSPasteboard, owner: Int32, token: String) -> CUClipboardSave {
        var unreadable: [String] = []
        let items = (board.pasteboardItems ?? []).map { item in
            CUClipboardItem(entries: item.types.compactMap { type in
                if let data = item.data(forType: type) { return CUClipboardEntry(type: type.rawValue, data: data) }
                unreadable.append(type.rawValue)
                return nil
            })
        }
        return CUClipboardSave(owner: owner, token: token, items: items, unreadable: unreadable)
    }

    static func writeAgentContent(_ content: CUPasteContent, token: String, to board: NSPasteboard) {
        board.clearContents()
        let item = NSPasteboardItem()
        if let html = content.html { item.setString(html, forType: .html) }
        item.setString(content.plain, forType: .string)
        item.setData(Data(), forType: cuTransientType)
        item.setData(Data(), forType: cuAutoGeneratedType)
        item.setString(token, forType: cuAgentTokenType)
        board.writeObjects([item])
    }

    static func boardToken(_ board: NSPasteboard) -> String? { board.string(forType: cuAgentTokenType) }

    static func restore(_ save: CUClipboardSave, to board: NSPasteboard) {
        board.clearContents()
        let items = save.items.map { saved -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in saved.entries { item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type)) }
            return item
        }
        if !items.isEmpty { board.writeObjects(items) }
    }

    static func persist(_ save: CUClipboardSave) -> URL? {
        let file = directory.appendingPathComponent("clipboard-\(save.owner)-\(save.token).plist")
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try cuEncodeClipboardSave(save).write(to: file, options: [.atomic])
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            return file
        } catch {
            FileHandle.standardError.write(Data("ace-screen-helper: could not save the clipboard: \(error)\n".utf8))
            return nil
        }
    }

    /// Puts back the clipboard of the paste in progress, if any. Used at exit.
    static func restorePending() {
        guard let pending else { return }
        let board = NSPasteboard.general
        if cuShouldRestore(pending.save, boardToken: boardToken(board), ownerAlive: true, isMine: true) { restore(pending.save, to: board) }
        try? FileManager.default.removeItem(at: pending.file)
        self.pending = nil
    }

    /// After a crash: restores a clipboard a dead helper saved, while the pasteboard still
    /// holds that helper's agent content; discards saves that no longer apply.
    static func recoverLeftovers(alive: (Int32) -> Bool = { kill($0, 0) == 0 }) {
        guard let files = try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil) else { return }
        let board = NSPasteboard.general
        let me = getpid()
        for file in files where file.lastPathComponent.hasPrefix("clipboard-") {
            guard let data = try? Data(contentsOf: file), let save = cuDecodeClipboardSave(data) else {
                try? FileManager.default.removeItem(at: file)
                continue
            }
            let ownerAlive = save.owner != me && alive(save.owner)
            if ownerAlive { continue }
            if cuShouldRestore(save, boardToken: boardToken(board), ownerAlive: false, isMine: false) { restore(save, to: board) }
            try? FileManager.default.removeItem(at: file)
        }
    }
}

/// An exclusive advisory lock shared by every helper process; the kernel drops it when the
/// holder exits, so it can never go stale.
final class CUFileLock {
    private let descriptor: Int32

    private init(descriptor: Int32) { self.descriptor = descriptor }

    /// Nil if the lock could not be taken within `timeoutMs` (the caller proceeds unlocked).
    static func acquire(path: String, timeoutMs: UInt64) async -> CUFileLock? {
        let descriptor = open(path, O_CREAT | O_RDWR | O_CLOEXEC, 0o600)
        guard descriptor >= 0 else { return nil }
        let started = cuNow()
        while flock(descriptor, LOCK_EX | LOCK_NB) != 0 {
            if cuNow() - started > timeoutMs * 1_000_000 { close(descriptor); return nil }
            try? await Task.sleep(nanoseconds: 20_000_000)
        }
        return CUFileLock(descriptor: descriptor)
    }

    deinit {
        flock(descriptor, LOCK_UN)
        close(descriptor)
    }
}
