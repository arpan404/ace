use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime};

use report::Report;
use units::{megabytes, millis, thousands};
use wire::Wire;

fn main() {
    if let Err(error) = run() {
        eprintln!("checkout bench: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), Box<dyn Error>> {
    let options = Options::parse(std::env::args().skip(1))?;
    let mut report = Report::new(format!(
        "ace-files checkout bench: {} files",
        thousands(options.files)
    ));
    let outcome = bench(&options, &mut report);
    if let Err(error) = &outcome {
        report.fail(error.to_string());
    }
    report.print();
    let published = report.write_json(&options.json);
    match (outcome, published) {
        (Ok(()), Ok(())) => {
            println!("wrote {}", options.json.display());
            Ok(())
        }
        (Ok(()), Err(error)) => Err(error),
        (Err(error), Ok(())) => {
            println!(
                "wrote {} (status {})",
                options.json.display(),
                report.status()
            );
            Err(error)
        }
        (Err(error), Err(publish)) => {
            eprintln!("cannot write {}: {publish}", options.json.display());
            Err(error)
        }
    }
}

/// The run itself: prepare the tree, start the binary, measure, stop it.
fn bench(options: &Options, report: &mut Report) -> Result<(), Box<dyn Error>> {
    let tree = tree::ensure(&options.dir, options.files, options.regenerate)?;
    report.retitle(format!(
        "ace-files checkout bench: {} files in {} folders",
        thousands(tree.shape.files),
        thousands(tree.shape.folders())
    ));
    report.fact("tree", tree.root.display().to_string());
    report.fact(
        "tree state",
        if tree.generated {
            "generated"
        } else {
            "reused"
        },
    );
    report.fact(
        "tree check",
        match tree.checked {
            Some(check) => format!(
                "{} files validated in {:.1} ms",
                thousands(check.files),
                millis(check.elapsed)
            ),
            None => "generated by this run".to_owned(),
        },
    );
    report.fact(
        "content",
        format!(
            "{:.0} MB in {} source files, {} node_modules files, {} in one folder",
            megabytes(tree.bytes),
            thousands(tree.shape.source_files),
            thousands(tree.shape.node_files),
            thousands(tree.shape.big_files)
        ),
    );
    report.fact("load", host::load_average());
    report.fact("memory", host::memory());
    report.fact("cache", cache_conditions(&tree));
    report.fact("machine", host::machine());
    let binary = binary();
    report.fact("binary", binary.display().to_string());

    let mut wire = Wire::start(&binary)?;
    wire.hello()?;
    let outcome = measure::measure(&mut wire, &tree, options, report);
    wire.stop();
    outcome
}

/// What the run was asked for.
pub struct Options {
    files: usize,
    dir: PathBuf,
    /// Where the JSON copy goes.
    pub json: PathBuf,
    regenerate: bool,
}

impl Options {
    fn parse(args: impl Iterator<Item = String>) -> Result<Options, Box<dyn Error>> {
        let mut options = Options {
            files: 1_000_000,
            dir: std::env::var_os("ACE_FILES_BENCH_DIR")
                .map(PathBuf::from)
                .unwrap_or_else(|| PathBuf::from("/var/tmp/ace-files-bench")),
            json: target_dir().join("bench/checkout.json"),
            regenerate: false,
        };
        let mut args = args;
        while let Some(arg) = args.next() {
            match arg.as_str() {
                "--files" => {
                    let value = args.next().ok_or("--files needs a count")?;
                    options.files = value
                        .parse()
                        .map_err(|error| format!("--files {value}: {error}"))?;
                }
                "--dir" => {
                    let value = args.next().ok_or("--dir needs a path")?;
                    if value.is_empty() {
                        return Err("--dir needs a path".into());
                    }
                    options.dir = PathBuf::from(value);
                }
                "--json" => {
                    options.json = PathBuf::from(args.next().ok_or("--json needs a path")?);
                }
                "--regenerate" => options.regenerate = true,
                // Cargo passes this to every bench executable; a harness-less bench ignores it.
                "--bench" => {}
                "--help" | "-h" => {
                    println!(
                        "cargo bench -p ace-files --bench checkout -- [--files N] [--dir PATH] [--json PATH] [--regenerate]"
                    );
                    std::process::exit(0);
                }
                other => return Err(format!("unknown argument {other}").into()),
            }
        }
        if options.files == 0 {
            return Err("--files needs at least one file".into());
        }
        Ok(options)
    }
}

/// The release binary `cargo bench` built beside this bench.
fn binary() -> PathBuf {
    if let Some(path) = std::env::var_os("ACE_FILES_BIN") {
        return PathBuf::from(path);
    }
    if let Some(path) = option_env!("CARGO_BIN_EXE_ace-files") {
        return PathBuf::from(path);
    }
    target_dir().join("release/ace-files")
}

/// The workspace's target folder.
fn target_dir() -> PathBuf {
    if let Some(path) = std::env::var_os("CARGO_TARGET_DIR") {
        return PathBuf::from(path);
    }
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    match fs::canonicalize(manifest.join("../..")) {
        Ok(workspace) => workspace.join("target"),
        Err(_) => manifest.join("../../target"),
    }
}

/// How warm the OS's cache should be for this run: a tree it just wrote is warm, and a reused
/// tree is as old as its completion marker, with its entries read once by the inventory check.
fn cache_conditions(tree: &tree::Tree) -> String {
    if tree.generated {
        return "warm: this run wrote every file".to_owned();
    }
    let Some(completed) = tree.completed else {
        return "reused: when the tree was written is unknown".to_owned();
    };
    match SystemTime::now().duration_since(completed) {
        Ok(age) => format!(
            "reused: files last written {} ago; the check read every entry, so metadata is warm",
            age_phrase(age)
        ),
        Err(_) => "reused: the marker's time is in the future".to_owned(),
    }
}

/// A short way to say an age, in the unit a person would use.
fn age_phrase(age: Duration) -> String {
    let seconds = age.as_secs();
    if seconds < 120 {
        format!("{seconds} s")
    } else if seconds < 2 * 60 * 60 {
        format!("{} min", seconds / 60)
    } else if seconds < 2 * 24 * 60 * 60 {
        format!("{} h", seconds / 3600)
    } else {
        format!("{} days", seconds / 86_400)
    }
}
