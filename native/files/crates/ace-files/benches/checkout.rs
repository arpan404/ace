//! End-to-end timings of the real `ace-files` binary on a million-file checkout.
//!
//! Run with `cargo bench -p ace-files --bench checkout`; `-- --files 100000` measures a tenth of
//! the tree for a quick check, `-- --dir PATH` picks where the tree lives (or set
//! `ACE_FILES_BENCH_DIR`), and `-- --regenerate` replaces a tree at that path. The tree is left
//! behind for the next run: the ownership marker the bench creates first is what lets a later run
//! replace it, and the completion marker written last is what says it is complete. A completion
//! marker alone never makes a folder the bench's.
//!
//! A run only ever empties a folder it created, or an empty one: `--regenerate` refuses a
//! non-empty `--dir` that does not carry the bench's ownership marker, refuses a folder that is a
//! symlink, takes an exclusive lock on the folder for the run, and `--files` must be at least one.
//! The watcher and burst write into a fresh scratch folder of their own that the run removes.
//!
//! Everything is measured over the wire against the release binary: the first folder page, the
//! quick-open index, a literal content search sized to two gigabytes, watcher latency and a burst
//! that makes the watcher give up on individual changes. Numbers go to a table and to
//! `target/bench/checkout.json` (or `--json PATH`), which is published even when a step fails, with
//! its status and the reason. Set `ACE_BENCH_VERBOSE` to print what the watcher reported.

