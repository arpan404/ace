//! Shell templates in the shapes coding agents write (ADR 0172, amendment 1): reads chained with
//! `;`, `&&` and `echo '---'` separators, `2>&1 | tail`, builds and checks, files written or edited
//! through here-documents, commit messages from `cat <<'EOF'`, and the risky commands that come in
//! the same shapes: a push after a commit, a PR comment from a here-document, a token in a header.
//! Written fresh for this purpose; split and filled like `shell_families`.

use spade_core::effect::Effect::*;

use crate::shell_families::Family;

const fn family(
    name: &'static str,
    label: spade_core::effect::Effect,
    variants: &'static [&'static str],
) -> Family {
    Family {
        name,
        label,
        variants,
    }
}

