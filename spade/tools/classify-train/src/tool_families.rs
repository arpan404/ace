//! Tool-call templates by what the call does: base names (snake case, restyled when generated)
//! and the argument sets such a tool takes. Values are filled from `vocab` by kind. The
//! adversarial families are only ever test data: names that hide what the arguments show.

use spade_core::effect::Effect::{self, *};

/// What an argument's value is.
#[derive(Debug, Clone, Copy)]
pub enum Val {
    Text,
    Message,
    Email,
    Phone,
    Url,
    Id,
    Number,
    Amount,
    Currency,
    Bool(bool),
    Role,
    Path,
    Labels,
    Fields,
    Env,
    Version,
    Selector,
    Key,
    Command(Effect),
}

pub struct ToolFamily {
    pub name: &'static str,
    pub label: Effect,
    pub bases: &'static [&'static str],
    pub arguments: &'static [&'static [(&'static str, Val)]],
    /// How often its server marks it read-only.
    pub read_only: f64,
    /// Only test data.
    pub adversarial: bool,
}

use Val::*;

const fn fam(
    name: &'static str,
    label: Effect,
    bases: &'static [&'static str],
    arguments: &'static [&'static [(&'static str, Val)]],
    read_only: f64,
) -> ToolFamily {
    ToolFamily {
        name,
        label,
        bases,
        arguments,
        read_only,
        adversarial: false,
    }
}

const fn odd(
    name: &'static str,
    label: Effect,
    bases: &'static [&'static str],
    arguments: &'static [&'static [(&'static str, Val)]],
) -> ToolFamily {
    ToolFamily {
        name,
        label,
        bases,
        arguments,
        // Servers that hide a write often claim to read.
        read_only: 0.5,
        adversarial: true,
    }
}

