#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_hard_set_has_every_effect_and_no_command_twice() {
        let mut seen: Vec<&str> = HARD.iter().map(|(c, _)| *c).collect();
        seen.sort_unstable();
        let before = seen.len();
        seen.dedup();
        assert_eq!(seen.len(), before, "a command is in the hard set twice");
        for effect in spade_classify::CLASSES {
            assert!(HARD.iter().any(|(_, e)| *e == effect), "{effect:?}");
        }
    }
}
