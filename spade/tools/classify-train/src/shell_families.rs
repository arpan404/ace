//! Shell command templates by what they do. Each family is one intent with several surface
//! forms (variants); variants are split between training, validation and test, so a held-out
//! set never shares a form with training. `{name}` is filled from `vocab`.

use spade_core::effect::Effect::{self, *};

pub struct Family {
    pub name: &'static str,
    pub label: Effect,
    pub variants: &'static [&'static str],
}

const fn family(name: &'static str, label: Effect, variants: &'static [&'static str]) -> Family {
    Family {
        name,
        label,
        variants,
    }
}

