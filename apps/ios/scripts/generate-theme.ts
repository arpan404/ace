import { DesignTokensSchema } from "@ace/design-tokens";
import data from "@ace/design-tokens/tokens.json" with { type: "json" };
import {
  accentNames,
  phoneAccentIds,
  phoneColourRoles,
  phoneOverrides,
  themeIds,
  themes,
  transcriptScale,
  transcriptSizeIds,
  transcriptSizes,
} from "@ace/themes";
import { readFile, writeFile } from "node:fs/promises";

// Validate the raw JSON here too. A generator must never silently accept an incompatible schema.
const tokens = DesignTokensSchema.parse(data);
// Editable keys match NativePalette.editable in apps/ios/Shared/NativePalette.swift.
// Status, statusText and semantic surfaces keep their shared meanings and stay fixed.
const editableColours = [
  "background",
  "secondaryBackground",
  "card",
  "foreground",
  "mutedForeground",
  "subtleForeground",
  "separator",
  "fill",
  "accent",
  "onAccent",
] as const;
// Theme roles (`@ace/themes` phoneColourRoles) resolve live too, so a theme switch redraws them.
const isDynamic = (key: string): boolean =>
  (editableColours as readonly string[]).includes(key) ||
  (phoneColourRoles as readonly string[]).includes(key);
const hex = (value: string | undefined): string => {
  if (value === undefined) throw new Error("Missing token colour value.");
  return value.slice(1);
};
const lightColours: Record<string, string> = tokens.schemes.light.colours;
const darkColours: Record<string, string> = tokens.schemes.dark.colours;
const lines = [
  "// Generated by scripts/generate-theme.ts from @ace/design-tokens/tokens.json. Do not edit.",
  "import SwiftUI",
  "import UIKit",
  "",
  "@MainActor enum AceTheme {",
  "    /// UIKit also resolves dynamic colours on SwiftUI's render threads, so the provider is",
  "    /// nonisolated and touches nothing but its captured values.",
  "    nonisolated private static func adaptive(_ light: UInt32, _ dark: UInt32) -> Color {",
  "        Color(uiColor: UIColor { @Sendable traits in",
  "            let value = traits.userInterfaceStyle == .dark ? dark : light",
  "            return UIColor(red: CGFloat((value >> 16) & 255) / 255, green: CGFloat((value >> 8) & 255) / 255, blue: CGFloat(value & 255) / 255, alpha: 1)",
  "        })",
  "    }",
  "    /// Token defaults for the editable palette keys, which a saved palette overrides.",
  "    /// Widget extensions never register a model and keep these shared defaults.",
  "    static let paletteDefaults: [String: NativePalette.Pair] = [",
  ...editableColours.map(
    (key) =>
      `        "${key}": .init(light: 0x${hex(lightColours[key])}, dark: 0x${hex(darkColours[key])}),`,
  ),
  "    ]",
  "    /// Each theme's colours under each accent (`@ace/themes` phoneOverrides): theme id → accent",
  "    /// id → role → pair. A role a theme leaves out keeps its token colour.",
  "    static let themeOverrides: [String: [String: [String: NativePalette.Pair]]] = [",
  ...themeIds.flatMap((theme) => [
    `        "${theme}": [`,
    ...phoneAccentIds.flatMap((accent) => {
      const light = phoneOverrides(theme, accent, "light");
      const dark = phoneOverrides(theme, accent, "dark");
      const roles = phoneColourRoles.filter((role) => light[role] || dark[role]);
      if (roles.length === 0) return [`            "${accent}": [:],`];
      return [
        `            "${accent}": [`,
        ...roles.map(
          (role) =>
            `                "${role}": .init(light: 0x${hex(light[role] ?? lightColours[role])}, dark: 0x${hex(dark[role] ?? darkColours[role])}),`,
        ),
        "            ],",
      ];
    }),
    "        ],",
  ]),
  "    ]",
  "    /// The themes and accents Settings offers, in order, as (id, name).",
  `    static let themeChoices: [(id: String, name: String)] = [${themeIds.map((id) => `("${id}", "${themes[id].name}")`).join(", ")}]`,
  `    static let accentChoices: [(id: String, name: String)] = [${phoneAccentIds.map((id) => `("${id}", "${accentNames[id]}")`).join(", ")}]`,
  "    /// Transcript sizes as (id, name, scale): the scale multiplies the Dynamic Type size.",
  `    static let transcriptSizes: [(id: String, name: String, scale: CGFloat)] = [${transcriptSizeIds.map((id) => `("${id}", "${transcriptSizes[id].label}", ${transcriptScale(id).toFixed(4)})`).join(", ")}]`,
  "    /// A role's colour pair in any theme and accent, for previews of choices not on screen.",
  "    static func pair(_ role: String, theme: String, accent: String) -> NativePalette.Pair? {",
  "        themeOverrides[theme]?[accent]?[role] ?? tokenPairs[role]",
  "    }",
  "    static let tokenPairs: [String: NativePalette.Pair] = [",
  ...phoneColourRoles.map(
    (key) =>
      `        "${key}": .init(light: 0x${hex(lightColours[key])}, dark: 0x${hex(darkColours[key])}),`,
  ),
  "    ]",
  "    /// Editable colours resolve through the injected model so saves and resets",
  "    /// invalidate every active view. Semantic colours below stay fixed.",
];
lines.push("    @MainActor enum Colours {");
for (const key of Object.keys(tokens.schemes.light.colours)) {
  const lightHex = hex(lightColours[key]);
  const darkHex = hex(darkColours[key]);
  if (isDynamic(key)) {
    lines.push(
      `        static var ${key}: Color {`,
      `            let pair = NativePaletteBridge.pair(for: "${key}", light: 0x${lightHex}, dark: 0x${darkHex})`,
      "            return adaptive(pair.light, pair.dark)",
      "        }",
    );
  } else {
    lines.push(`        static let ${key} = adaptive(0x${lightHex}, 0x${darkHex})`);
  }
}
lines.push("    }");
for (const group of ["status", "statusText"] as const) {
  lines.push(`    @MainActor enum ${group === "status" ? "Status" : "StatusText"} {`);
  for (const key of Object.keys(tokens.schemes.light[group])) {
    const values: Record<string, string> = tokens.schemes.light[group];
    const dark: Record<string, string> = tokens.schemes.dark[group];
    lines.push(`        static let ${key} = adaptive(0x${hex(values[key])}, 0x${hex(dark[key])})`);
  }
  lines.push("    }");
}
for (const group of ["spacing", "radii", "dimensions", "elevation"] as const) {
  lines.push(`    enum ${group[0]?.toUpperCase()}${group.slice(1)} {`);
  for (const [key, value] of Object.entries(tokens[group]))
    lines.push(`        static let ${key}: CGFloat = ${value}`);
  lines.push("    }");
}
lines.push("    enum Opacity {");
for (const key of Object.keys(tokens.schemes.light.opacity)) {
  const light: Record<string, number> = tokens.schemes.light.opacity;
  const dark: Record<string, number> = tokens.schemes.dark.opacity;
  lines.push(
    `        static func ${key}(_ scheme: ColorScheme) -> Double { scheme == .dark ? ${dark[key]} : ${light[key]} }`,
  );
}
lines.push("    }", "    enum Motion {");
for (const [key, value] of Object.entries(tokens.motion))
  if (typeof value === "number") lines.push(`        static let ${key}: Double = ${value / 1000}`);
for (const [key, points] of Object.entries(tokens.motion.easing)) {
  lines.push(
    `        static let ${key}Curve = Animation.timingCurve(${points.join(", ")}, duration: ${tokens.motion[key === "standard" ? "standard" : key === "enter" ? "enter" : "exit"] / 1000})`,
  );
}
lines.push("        static let spring = Animation.spring(duration: enter)");
lines.push(
  "    }",
  "    struct TypeStyle: Sendable { let size: CGFloat; let lineHeight: CGFloat; let weight: CGFloat; let tracking: CGFloat }",
  "    enum Typography {",
);
for (const [key, value] of Object.entries(tokens.typography.typeScale))
  lines.push(
    `        static let ${key} = TypeStyle(size: ${value.size}, lineHeight: ${value.lineHeight}, weight: ${value.weight}, tracking: ${value.letterSpacing})`,
  );
lines.push(`    }
    static func fontWeight(_ value: CGFloat) -> Font.Weight {
        switch value {
        case 500: .medium
        case 600: .semibold
        case 700: .bold
        default: .regular
        }
    }
    static func uiFont(_ style: TypeStyle, relativeTo: UIFont.TextStyle, traits: UITraitCollection) -> UIFont {
        let weight: UIFont.Weight = switch style.weight {
        case 500: .medium
        case 600: .semibold
        case 700: .bold
        default: .regular
        }
        return UIFontMetrics(forTextStyle: relativeTo).scaledFont(for: .systemFont(ofSize: style.size, weight: weight), compatibleWith: traits)
    }
    static func inputAttributes(traits: UITraitCollection) -> [NSAttributedString.Key: Any] {
        let style = Typography.body
        let font = uiFont(style, relativeTo: .body, traits: traits)
        let paragraph = NSMutableParagraphStyle()
        paragraph.minimumLineHeight = UIFontMetrics(forTextStyle: .body).scaledValue(for: style.lineHeight, compatibleWith: traits)
        paragraph.maximumLineHeight = paragraph.minimumLineHeight
        return [.font: font, .foregroundColor: UIColor(Colours.foreground), .paragraphStyle: paragraph, .kern: style.tracking * font.pointSize / style.size]
    }
}

@MainActor private struct AceTokenFont: ViewModifier {
    let style: AceTheme.TypeStyle
    let design: Font.Design
    @ScaledMetric private var size: CGFloat
    @ScaledMetric private var lineHeight: CGFloat
    @ScaledMetric private var tracking: CGFloat
    @Environment(\\.transcriptScale) private var scale

    init(style: AceTheme.TypeStyle, relativeTo: Font.TextStyle, design: Font.Design) {
        self.style = style
        self.design = design
        _size = ScaledMetric(wrappedValue: style.size, relativeTo: relativeTo)
        _lineHeight = ScaledMetric(wrappedValue: style.lineHeight, relativeTo: relativeTo)
        _tracking = ScaledMetric(wrappedValue: style.tracking, relativeTo: relativeTo)
    }

    func body(content: Content) -> some View {
        let size = size * scale
        return content.font(.system(size: size, weight: AceTheme.fontWeight(style.weight), design: design))
            .tracking(tracking * scale)
            .lineSpacing(max(AceTheme.Spacing.none, lineHeight * scale - UIFont.systemFont(ofSize: size).lineHeight))
    }
}

extension EnvironmentValues {
    /// The transcript's size relative to Dynamic Type (Settings › Appearance): 1 everywhere else.
    @Entry var transcriptScale: CGFloat = 1
}

extension View {
    @MainActor func aceFont(_ style: AceTheme.TypeStyle, relativeTo: Font.TextStyle) -> some View {
        modifier(AceTokenFont(style: style, relativeTo: relativeTo, design: .default))
    }
    @MainActor func aceMonospace(_ style: AceTheme.TypeStyle, relativeTo: Font.TextStyle) -> some View {
        modifier(AceTokenFont(style: style, relativeTo: relativeTo, design: .monospaced))
    }
}
`);
const output = lines.join("\n");
const path = new URL("../Sources/Views/AceTheme.generated.swift", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== output)
    throw new Error("Swift theme is stale. Run bun run theme in apps/ios.");
} else await writeFile(path, output);
