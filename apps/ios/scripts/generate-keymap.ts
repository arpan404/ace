import {
  formatPhoneKeys,
  normalizePhoneKeys,
  phoneKeyProblem,
  phoneKeymap,
  phoneNamedKeys,
  phoneReservedKeys,
  resolvePhoneKeymap,
} from "@ace/ui-core/phone-keymap";
import { readFile, writeFile } from "node:fs/promises";

// The phone's shortcut table (`@ace/ui-core/phone-keymap`) as Swift, plus cases the TS rules
// decide, which a Swift test replays so the Swift reading of the table can't drift from it.

const swift = (value: string) => JSON.stringify(value);
const keys = [..."abcdefghijklmnopqrstuvwxyz0123456789", ..."[]\\;',./`-=", ...phoneNamedKeys];
const table = [
  "// Generated by scripts/generate-keymap.ts from @ace/ui-core/phone-keymap. Do not edit.",
  "",
  "/// The hardware-keyboard shortcuts, their default keys and how keys read.",
  "enum PhoneKeymapTable {",
  "    struct Entry: Sendable { let id: String; let label: String; let keys: String; let scope: String; let group: String; let fixed: Bool }",
  "    static let entries: [Entry] = [",
  ...phoneKeymap.map(
    (entry) =>
      `        Entry(id: ${swift(entry.id)}, label: ${swift(entry.label)}, keys: ${swift(entry.keys)}, scope: ${swift(entry.scope)}, group: ${swift(entry.group)}, fixed: ${entry.fixed === true}),`,
  ),
  "    ]",
  `    static let reserved: Set<String> = [${phoneReservedKeys.map(swift).join(", ")}]`,
  "    /// Every key a shortcut may end on, with its printed name.",
  "    static let keyNames: [String: String] = [",
  ...keys.map((key) => `        ${swift(key)}: ${swift(formatPhoneKeys(`mod+${key}`).slice(1))},`),
  "    ]",
  "    /// The keys in the order the editor offers them.",
  `    static let keyOrder: [String] = [${keys.map(swift).join(", ")}]`,
  "}",
  "",
].join("\n");

// Cases: spellings to normalise, and keys to check against a set of rebindings.
const spellings = [
  "mod+Shift+K",
  "ctrl+mod+s",
  "k",
  "shift+k",
  "mod+hyper+k",
  "mod+",
  "alt+mod+enter",
  "mod+]",
];
const checks: { keys: string; id: string; overrides: Record<string, string> }[] = [
  { keys: "mod+f", id: "newThread", overrides: {} },
  { keys: "mod+f", id: "newThread", overrides: { searchThreads: "mod+k" } },
  { keys: "mod+k", id: "newThread", overrides: { searchThreads: "mod+k" } },
  { keys: "mod+c", id: "newThread", overrides: {} },
  { keys: "mod+n", id: "send", overrides: {} },
  { keys: "shift+mod+n", id: "send", overrides: {} },
  { keys: "k", id: "send", overrides: {} },
  { keys: "mod+n", id: "newThread", overrides: {} },
];
const problem = (check: (typeof checks)[number]) => {
  const result = phoneKeyProblem(check.keys, check.id, resolvePhoneKeymap(check.overrides));
  return result?.kind === "taken" ? `taken:${result.by}` : (result?.kind ?? "");
};
const vectors = [
  "// Generated by scripts/generate-keymap.ts from @ace/ui-core/phone-keymap. Do not edit.",
  "",
  "/// What the TS rules decide for these inputs; PhoneKeymapTests replays them in Swift.",
  "enum PhoneKeymapVectors {",
  "    static let spellings: [(input: String, normalized: String?)] = [",
  ...spellings.map((input) => {
    const out = normalizePhoneKeys(input);
    return `        (${swift(input)}, ${out === undefined ? "nil" : swift(out)}),`;
  }),
  "    ]",
  "    static let checks: [(keys: String, id: String, overrides: [String: String], problem: String)] = [",
  ...checks.map(
    (check) =>
      `        (${swift(check.keys)}, ${swift(check.id)}, [${Object.entries(check.overrides)
        .map(([id, value]) => `${swift(id)}: ${swift(value)}`)
        .join(", ")}${Object.keys(check.overrides).length ? "" : ":"}], ${swift(problem(check))}),`,
  ),
  "    ]",
  "    static let formats: [(keys: String, text: String)] = [",
  ...["ctrl+mod+s", "mod+enter", "shift+alt+mod+]", "mod+arrowup"].map(
    (value) => `        (${swift(value)}, ${swift(formatPhoneKeys(value))}),`,
  ),
  "    ]",
  "}",
  "",
].join("\n");

const outputs: [URL, string][] = [
  [new URL("../Sources/Views/Settings/PhoneKeymap.generated.swift", import.meta.url), table],
  [new URL("../Tests/PhoneKeymapVectors.generated.swift", import.meta.url), vectors],
];
for (const [path, text] of outputs) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== text)
      throw new Error("Swift keymap is stale. Run bun run keymap in apps/ios.");
  } else await writeFile(path, text);
}
